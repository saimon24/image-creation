// usage: node gen_ts.mjs <out.ts> -> writes the measured per-theme geometry (valleys/measure/*.json) as a TS module
import fs from 'node:fs';
const V = '/Users/ioannis/dev/ImageCreation/output/farm-map-v2/valleys';
const [out] = process.argv.slice(2);
const ids = fs.readdirSync(`${V}/measure`).filter((f) => f.endsWith('.json')).map((f) => f.replace('.json', '')).sort();
const pt = (p) => `{ x: ${p.x}, y: ${p.y} }`;
const pts = (a) => `[${a.map(([x, y]) => `[${x}, ${y}]`).join(', ')}]`;
let s = `// GENERATED by ImageCreation output/farm-map-v2/_pipeline/valleys/gen_ts.mjs from the measured
// theme paintings — do not edit by hand; re-measure and regenerate instead.
// Per theme: the scene rect inside its 2048x3072 painting, the centre of each painted plot
// (scene 0..1), its 15 decoration spots, what is painted that a decoration must keep off
// (paths, water, fields) and the walkways the villagers follow.

import type { BlockedShape } from './farm-map-deco-spots';
import type { ScenePoint } from './farm-map-layout';

export interface ThemeGeometry {
  scene: { left: number; top: number; width: number; height: number };
  plotCentres: Record<number, ScenePoint>;
  decorationPoints: Record<number, ScenePoint>;
  blocked: BlockedShape[];
  /** Each a painted path as a polyline in scene coordinates; the first and last point sit on a plot or the scene edge. */
  walkways: [number, number][][];
  edgeTone: string;
}

export const THEME_GEOMETRY: Record<string, ThemeGeometry> = {\n`;
for (const id of ids) {
  const m = JSON.parse(fs.readFileSync(`${V}/measure/${id}.json`, 'utf8'));
  s += `  ${id}: {\n    scene: ${JSON.stringify(m.scene).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ')},\n`;
  s += `    plotCentres: {\n${Object.entries(m.plotRings).map(([k, p]) => `      ${k}: ${pt(p)},`).join('\n')}\n    },\n`;
  s += `    decorationPoints: {\n${Object.entries(m.decorationPoints).map(([k, p]) => `      ${k}: ${pt(p)},`).join('\n')}\n    },\n`;
  s += `    blocked: [\n${m.blocked.map((b) => b.kind === 'ellipse'
    ? `      { kind: 'ellipse', label: '${b.label}', cx: ${b.cx}, cy: ${b.cy}, rx: ${b.rx}, ry: ${b.ry}${b.tall ? ', tall: true' : ''} },`
    : b.kind === 'poly' ? `      { kind: 'poly', label: '${b.label}', points: ${pts(b.points)}${b.tall ? ', tall: true' : ''} },`
    : `      { kind: 'path', label: '${b.label}', points: ${pts(b.points)}, width: ${b.width} },`).join('\n')}\n    ],\n`;
  s += `    walkways: [\n${m.walkways.map((w) => `      ${pts(w)},`).join('\n')}\n    ],\n`;
  s += `    edgeTone: '${m.edgeTone}',\n  },\n`;
}
s += '};\n';
fs.writeFileSync(out, s);
console.log(out, ids.length, 'themes');
